package javaTopics.reflection;

public class TP extends ParentTP {
    private int p;
    protected int z;
    public int t;
    int y;

    public int getP() {
        return p;
    }

    public void setP(int p) {
        this.p = p;
    }

    public int getZ() {
        return z;
    }

    public void setZ(int z) {
        this.z = z;
    }

    public int getT() {
        return t;
    }

    public void setT(int t) {
        this.t = t;
    }

    public int getY() {
        return y;
    }

    public void setY(int y) {
        this.y = y;
    }
}
